from __future__ import annotations

import argparse
import base64
from pathlib import Path

from PIL import Image, ImageOps


WORK_IDS = ("heungbu", "chunhyang", "honggildong", "simcheong", "byeoljubu", "jeonwoochi")


def cell(image: Image.Image, columns: int, rows: int, index: int, inset: float = 0) -> Image.Image:
    column = index % columns
    row = index // columns
    left = round(image.width * column / columns)
    top = round(image.height * row / rows)
    right = round(image.width * (column + 1) / columns)
    bottom = round(image.height * (row + 1) / rows)
    inset_x = round((right - left) * inset)
    inset_y = round((bottom - top) * inset)
    return image.crop((left + inset_x, top + inset_y, right - inset_x, bottom - inset_y))


def save_webp(image: Image.Image, output: Path, size: tuple[int, int], fit: bool = False) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    processed = ImageOps.fit(image, size, method=Image.Resampling.LANCZOS) if fit else ImageOps.contain(image, size, method=Image.Resampling.LANCZOS)
    if not fit:
        canvas = Image.new("RGBA", size, (0, 0, 0, 0))
        canvas.alpha_composite(processed.convert("RGBA"), ((size[0] - processed.width) // 2, (size[1] - processed.height) // 2))
        processed = canvas
    processed.save(output, "WEBP", quality=84, method=6)


def process_characters(atlas: Path, works: tuple[str, str, str], output_root: Path) -> None:
    with Image.open(atlas).convert("RGBA") as image:
        for index in range(9):
            work = works[index // 3]
            character_number = index % 3 + 1
            save_webp(cell(image, 3, 3, index, inset=0.065), output_root / "classics" / work / "characters" / f"character-{character_number:02d}.webp", (512, 512))


def process_backgrounds(atlas: Path, output_root: Path, scene_number: int = 1) -> None:
    with Image.open(atlas).convert("RGB") as image:
        for index, work in enumerate(WORK_IDS):
            save_webp(cell(image, 3, 2, index), output_root / "classics" / work / "backgrounds" / f"scene-{scene_number:02d}.webp", (960, 540), fit=True)


