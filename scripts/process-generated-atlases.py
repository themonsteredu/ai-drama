def write_typescript_bundle(output_root: Path, ts_output: Path) -> None:
    rows = [
        "// Generated by scripts/process-generated-atlases.py. Do not edit by hand.\n",
        "export const STAGE_ASSET_IMAGE_DATA: Record<string, string> = {\n",
    ]
    for image_path in sorted(output_root.rglob("*.webp")):
        key = image_path.relative_to(output_root).as_posix()
        encoded = base64.b64encode(image_path.read_bytes()).decode("ascii")
        rows.append(f'  "{key}": "{encoded}",\n')
    rows.append("};\n")
    ts_output.parent.mkdir(parents=True, exist_ok=True)
    ts_output.write_text("".join(rows), encoding="utf-8", newline="\n")


def write_typescript_bundle_parts(output_root: Path, ts_output_dir: Path) -> None:
    groups: dict[str, list[Path]] = {}
    for image_path in sorted(output_root.rglob("*.webp")):
        relative = image_path.relative_to(output_root)
        group = relative.parts[1] if relative.parts[0] == "classics" else relative.parts[0]
        groups.setdefault(group.replace("-", "_"), []).append(image_path)

    ts_output_dir.mkdir(parents=True, exist_ok=True)
    imports: list[str] = []
    names: list[str] = []
    for group, image_paths in groups.items():
        variable = f"imageData_{group}"
        names.append(variable)
        imports.append(f'import {{ {variable} }} from "./{group}.generated";\n')
        rows = [f"export const {variable}: Record<string, string> = {{\n"]
        for image_path in image_paths:
            key = image_path.relative_to(output_root).as_posix()
            encoded = base64.b64encode(image_path.read_bytes()).decode("ascii")
            rows.append(f'  "{key}": "{encoded}",\n')
        rows.append("};\n")
        (ts_output_dir / f"{group}.generated.ts").write_text("".join(rows), encoding="utf-8", newline="\n")

    index_rows = ["// Generated image bundle index.\n", *imports, "\nexport const STAGE_ASSET_IMAGE_DATA: Record<string, string> = Object.assign({},\n"]
    index_rows.extend(f"  {name},\n" for name in names)
    index_rows.append(");\n")
    (ts_output_dir / "index.ts").write_text("".join(index_rows), encoding="utf-8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--characters-a", type=Path, required=True)
    parser.add_argument("--characters-b", type=Path, required=True)
    parser.add_argument("--backgrounds", type=Path, required=True)
    parser.add_argument("--backgrounds-b", type=Path)
    parser.add_argument("--backgrounds-c", type=Path)
    parser.add_argument("--props", type=Path, required=True)
    parser.add_argument("--props-extra", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--ts-output", type=Path)
    args = parser.parse_args()

    print("Processing character atlas A...", flush=True)
    process_characters(args.characters_a, WORK_IDS[:3], args.output)
    print("Processing character atlas B...", flush=True)
    process_characters(args.characters_b, WORK_IDS[3:], args.output)
    print("Processing background atlas 1...", flush=True)
    process_backgrounds(args.backgrounds, args.output, 1)
    if args.backgrounds_b:
        print("Processing background atlas 2...", flush=True)
        process_backgrounds(args.backgrounds_b, args.output, 2)
    if args.backgrounds_c:
        print("Processing background atlas 3...", flush=True)
        process_backgrounds(args.backgrounds_c, args.output, 3)
    print("Processing prop atlas 1...", flush=True)
    process_props(args.props, args.output)
    if args.props_extra:
        print("Processing prop atlas 2...", flush=True)
        process_props_extra(args.props_extra, args.output)
    if args.ts_output:
        print("Writing TypeScript image bundle...", flush=True)
        write_typescript_bundle(args.output, args.ts_output)
    print("Done.", flush=True)


if __name__ == "__main__":
    main()
